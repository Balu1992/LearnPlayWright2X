// Assignment Operators starts with the equal sign (=) and are used to assign values to variables. They can also be combined with other operators to perform operations and assign the result to a variable in one step.
// Here are some common assignment operators in JavaScript:
let x=20;
console.log("X=",x);
let y=30;
console.log("X+Y=",x+y); 
y+=x+y; // y = y + (x + y) => y = 30 + (20 + 30) => y = 80
console.log("Y=",y); // Y=80