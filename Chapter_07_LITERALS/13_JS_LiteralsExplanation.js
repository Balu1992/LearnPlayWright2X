// Basic literals example for Chapter 07

// Numbers
const age = 34;
console.log('age:', age); // 34
console.log('typeof age:', typeof age); // 'number'

// Strings and template literals
const name = 'Balaji';
console.log('greeting:', `Hello, ${name}!`); // Hello, Balaji!

// Booleans
const isActive = true;
console.log('isActive:', isActive, 'typeof:', typeof isActive); // true 'boolean'

// null vs undefined (basic)
let notAssigned;
console.log('notAssigned:', notAssigned); // undefined

const nothing = null;
console.log('nothing:', nothing); // null

// Simple comparison notes
console.log('null == undefined ->', null == undefined); // true
console.log('null === undefined ->', null === undefined); // false

// End of basic examples

